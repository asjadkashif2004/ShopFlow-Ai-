"""Builds supabase/shoppilot_setup.sql: schema + access rules + the 60-product seed.

Run it again after changing data/catalog.seed.json or backend/app/schema.sql:
    backend/.venv/Scripts/python backend/scripts/build_supabase_sql.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = (ROOT / "backend" / "app" / "schema.sql").read_text(encoding="utf-8")
CATALOG = json.loads((ROOT / "data" / "catalog.seed.json").read_text(encoding="utf-8"))
OUT = ROOT / "supabase" / "shoppilot_setup.sql"


def lit(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def jsonb(v: object) -> str:
    return lit(json.dumps(v, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"


def text_array(items: list[str]) -> str:
    return "array[" + ", ".join(lit(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


POLICIES = """
-- ---------------------------------------------------------------------------
-- Access rules for the ShopPilot backend, which uses the publishable (anon) key.
-- Row Level Security stays on; these policies allow only what the app needs.
-- If you later give the backend the Supabase secret key, you can drop the
-- write policies below (the secret key bypasses RLS).
-- ---------------------------------------------------------------------------

drop policy if exists "shoppilot: read categories" on categories;
create policy "shoppilot: read categories" on categories for select to anon, authenticated using (true);

drop policy if exists "shoppilot: read products" on products;
create policy "shoppilot: read products" on products for select to anon, authenticated using (true);

drop policy if exists "shoppilot: read missions" on missions;
create policy "shoppilot: read missions" on missions for select to anon, authenticated using (true);
drop policy if exists "shoppilot: create missions" on missions;
create policy "shoppilot: create missions" on missions for insert to anon, authenticated with check (true);
drop policy if exists "shoppilot: finish missions" on missions;
create policy "shoppilot: finish missions" on missions for update to anon, authenticated using (true) with check (true);

drop policy if exists "shoppilot: log steps" on mission_steps;
create policy "shoppilot: log steps" on mission_steps for insert to anon, authenticated with check (true);

drop policy if exists "shoppilot: log recommendations" on recommendations;
create policy "shoppilot: log recommendations" on recommendations for insert to anon, authenticated with check (true);

drop policy if exists "shoppilot: read orders" on orders;
create policy "shoppilot: read orders" on orders for select to anon, authenticated using (true);
drop policy if exists "shoppilot: create orders" on orders;
create policy "shoppilot: create orders" on orders for insert to anon, authenticated with check (status = 'CREATED');
drop policy if exists "shoppilot: update orders" on orders;
create policy "shoppilot: update orders" on orders for update to anon, authenticated using (true) with check (true);

-- The catalog itself is read-only through the API. Stock changes go through this
-- function, which can only take one unit off one product.
create or replace function decrement_stock(p_product_id text)
returns void
language sql
security definer
set search_path = public
as $$
  update products set stock = greatest(stock - 1, 0), updated_at = now() where id = p_product_id;
$$;
revoke all on function decrement_stock(text) from public;
grant execute on function decrement_stock(text) to anon, authenticated;
"""


def opt(s: str | None) -> str:
    return lit(s) if s else "null"


def image_values(p: dict) -> str:
    img = p.get("image") or {}
    return f"{opt(img.get('url'))}, {opt(img.get('credit'))}, {opt(img.get('creditUrl'))}"


def build_images_migration() -> str:
    """Adds photos to a database that was set up before photos existed. Keeps stock and orders."""
    rows = [f"  ({lit(p['id'])}, {image_values(p)})" for p in CATALOG["products"] if p.get("image")]
    return "\n".join(
        [
            "-- ShopPilot: add product photos. Generated by backend/scripts/build_supabase_sql.py.",
            "-- Paste into Supabase → SQL Editor → New query, then click Run. Safe to run more than once.",
            "-- Only adds three columns and fills them; stock, orders and missions are untouched.",
            "",
            "begin;",
            "",
            "alter table products add column if not exists image_url text;",
            "alter table products add column if not exists image_credit text;",
            "alter table products add column if not exists image_credit_url text;",
            "",
            "update products as p",
            "set image_url = v.image_url, image_credit = v.image_credit, image_credit_url = v.image_credit_url, updated_at = now()",
            "from (values",
            ",\n".join(rows),
            ") as v(id, image_url, image_credit, image_credit_url)",
            "where p.id = v.id;",
            "",
            "commit;",
            "",
            "-- Ask the Supabase API to pick up the new columns right away.",
            "notify pgrst, 'reload schema';",
            "",
        ]
    )


def build() -> str:
    parts = [
        "-- ShopPilot setup for Supabase. Generated by backend/scripts/build_supabase_sql.py.",
        "-- Paste the whole file into Supabase → SQL Editor → New query, then click Run.",
        "-- Safe to run more than once.",
        "",
        "begin;",
        "",
        SCHEMA.strip(),
        POLICIES.strip(),
        "",
        "-- ---------------------------------------------------------------------------",
        f"-- Seed: {len(CATALOG['categories'])} categories and {len(CATALOG['products'])} products (fictional brands)",
        "-- ---------------------------------------------------------------------------",
        "insert into categories (slug, name, singular, key_specs, specs, sort_order) values",
    ]
    cat_rows = [
        f"  ({lit(c['slug'])}, {lit(c['name'])}, {lit(c['singular'])}, {text_array(c['keySpecs'])}, {jsonb(c['specs'])}, {i})"
        for i, c in enumerate(CATALOG["categories"])
    ]
    parts.append(",\n".join(cat_rows))
    parts.append(
        "on conflict (slug) do update set name = excluded.name, singular = excluded.singular,\n"
        "  key_specs = excluded.key_specs, specs = excluded.specs, sort_order = excluded.sort_order;"
    )
    parts.append("")
    parts.append(
        "insert into products (id, category, name, brand, price, rating, review_count, stock, description, specs, tags,\n"
        "  image_url, image_credit, image_credit_url) values"
    )
    prod_rows = [
        f"  ({lit(p['id'])}, {lit(p['category'])}, {lit(p['name'])}, {lit(p['brand'])}, {p['price']:.2f}, {p['rating']:.1f}, "
        f"{p['reviewCount']}, {p['stock']}, {lit(p['description'])}, {jsonb(p['specs'])}, {text_array(p['tags'])}, "
        f"{image_values(p)})"
        for p in CATALOG["products"]
    ]
    parts.append(",\n".join(prod_rows))
    parts.append(
        "on conflict (id) do update set category = excluded.category, name = excluded.name, brand = excluded.brand,\n"
        "  price = excluded.price, rating = excluded.rating, review_count = excluded.review_count,\n"
        "  description = excluded.description, specs = excluded.specs, tags = excluded.tags,\n"
        "  image_url = excluded.image_url, image_credit = excluded.image_credit, image_credit_url = excluded.image_credit_url,\n"
        "  updated_at = now();"
    )
    parts += ["", "commit;", "", "-- Ask the Supabase API to pick up the new tables right away.", "notify pgrst, 'reload schema';", ""]
    return "\n".join(parts)


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes)")
    images = OUT.parent / "002_product_images.sql"
    images.write_text(build_images_migration(), encoding="utf-8")
    print(f"Wrote {images.relative_to(ROOT)} ({images.stat().st_size:,} bytes)")
